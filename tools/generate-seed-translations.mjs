#!/usr/bin/env node
/**
 * Generates the seed-translations.sql file for the backend dev/test profile.
 *
 * Reads the four locale TypeScript files (en.ts, pt-br.ts, es.ts, it.ts)
 * and produces a single SQL file with INSERT statements for ui_translations.
 *
 * Usage:
 *   node tools/generate-seed-translations.mjs
 *
 * The output is written to:
 *   ../portfolio-blog-backend/src/main/resources/dev/seed-translations.sql
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const I18N_DIR = path.resolve(__dirname, '../src/app/core/services/i18n');
const OUTPUT_PATH = path.resolve(
    __dirname, '../../portfolio-blog-backend/src/main/resources/dev/seed-translations.sql'
);

const LOCALES = [
    { code: 'en',    file: 'en.ts',    exportName: 'en' },
    { code: 'pt-br', file: 'pt-br.ts', exportName: 'ptBr' },
    { code: 'es',    file: 'es.ts',    exportName: 'es' },
    { code: 'it',    file: 'it.ts',    exportName: 'it' },
];

/**
 * Parse a TypeScript locale file and return a Map of key to value.
 * Handles single-quoted and double-quoted values with escaped characters.
 */
function parseLocaleFile(filePath) {
    const content = fs.readFileSync(filePath, 'utf8');
    const entries = new Map();

    /** Decode \\uXXXX escape sequences to actual Unicode characters. */
    function decodeUnicodeEscapes(str) {
        return str.replace(/\\u([0-9a-fA-F]{4})/g, (_, hex) => String.fromCharCode(parseInt(hex, 16)));
    }

    // Match: 'key.name': 'value content',
    const sqRegex = /^\s+'([a-zA-Z0-9_.]+)'\s*:\s*'((?:[^'\\]|\\.)*)'/gm;
    let m;
    while ((m = sqRegex.exec(content)) !== null) {
        let val = m[2].replace(/\\'/g, "'").replace(/\\\\/g, '\\');
        entries.set(m[1], decodeUnicodeEscapes(val));
    }

    // Match: 'key.name': "value content",
    const dqRegex = /^\s+'([a-zA-Z0-9_.]+)'\s*:\s*"((?:[^"\\]|\\.)*)"/gm;
    while ((m = dqRegex.exec(content)) !== null) {
        if (!entries.has(m[1])) {
            let val = m[2].replace(/\\"/g, '"').replace(/\\\\/g, '\\');
            entries.set(m[1], decodeUnicodeEscapes(val));
        }
    }

    return entries;
}

/**
 * Escape a string value for SQL single-quote literals.
 */
function escapeSQL(value) {
    if (value == null) return '';
    return value.replace(/'/g, "''");
}

/**
 * Determine the visibility tier based on the translation key prefix.
 */
function visibility(key) {
    if (key.startsWith('admin.')) return 'admin';
    if (key.startsWith('dev.'))   return 'dev';
    if (key.startsWith('account.') || key.startsWith('viewer.')) return 'viewer';
    return 'public';
}

// --- Main ---

console.log('Reading locale files...');
const allLocales = new Map();

for (const locale of LOCALES) {
    const filePath = path.join(I18N_DIR, locale.file);
    if (!fs.existsSync(filePath)) {
        console.warn('  WARN: ' + locale.file + ' not found, skipping locale ' + locale.code);
        continue;
    }
    const entries = parseLocaleFile(filePath);
    console.log('  ' + locale.code + ': ' + entries.size + ' keys');
    allLocales.set(locale.code, entries);
}

// Use English keys as the canonical key set
const enKeys = allLocales.get('en');
if (!enKeys) {
    console.error('ERROR: en.ts not found or empty!');
    process.exit(1);
}

// Generate SQL
const lines = [];
lines.push('-- =======================================================================');
lines.push('-- Seed translations for all supported locales (en, pt-br, es, it).');
lines.push('-- Generated by: tools/generate-seed-translations.mjs');
lines.push('-- Generated at: ' + new Date().toISOString());
lines.push('--');
lines.push('-- This file is loaded by DevDataInitializer on dev/test profiles only.');
lines.push('-- The COUNT guard in DevDataInitializer prevents re-seeding when');
lines.push('-- translations already exist.');
lines.push('-- =======================================================================');
lines.push('');

let id = 100001; // High base to avoid Snowflake ID collisions
let totalRows = 0;

for (const [localeCode, entries] of allLocales) {
    lines.push('-- ' + localeCode.toUpperCase() + ' ' + '-'.repeat(70));
    lines.push('');

    for (const [key, value] of entries) {
        const vis = visibility(key);
        lines.push(
            "INSERT INTO ui_translations (id, translation_key, locale, \"value\", namespace, visibility) VALUES ("
            + id + ", '" + escapeSQL(key) + "', '" + localeCode + "', '"
            + escapeSQL(value) + "', 'frontend', '" + vis + "');"
        );
        id++;
        totalRows++;
    }

    lines.push('');
}

// Insert fallbacks: keys that exist in English but are missing in other locales
for (const [localeCode, entries] of allLocales) {
    if (localeCode === 'en') continue;
    let fallbackCount = 0;
    for (const [key, enValue] of enKeys) {
        if (!entries.has(key)) {
            const vis = visibility(key);
            lines.push(
                "INSERT INTO ui_translations (id, translation_key, locale, \"value\", namespace, visibility) VALUES ("
                + id + ", '" + escapeSQL(key) + "', '" + localeCode + "', '"
                + escapeSQL(enValue) + "', 'frontend', '" + vis + "');"
            );
            id++;
            totalRows++;
            fallbackCount++;
        }
    }
    if (fallbackCount > 0) {
        console.log('  ' + localeCode + ': ' + fallbackCount + ' keys fell back to English');
    }
}

// Write file
fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
fs.writeFileSync(OUTPUT_PATH, lines.join('\n') + '\n', 'utf8');

const fileSize = Buffer.byteLength(lines.join('\n'), 'utf8');
console.log('');
console.log('Generated: ' + OUTPUT_PATH);
console.log('Total rows: ' + totalRows);
console.log('File size: ' + (fileSize / 1024).toFixed(1) + ' KB');
